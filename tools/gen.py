def esc(s): return html.escape(s, quote=False)

def nav_html(prefix, active):
    return "\n".join(
        f'<a href="{prefix}{h}"{" class=\"active\"" if h == active else ""}>{esc(l)}</a>'
        for h, l in NAV)

