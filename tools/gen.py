def stat_rows(pairs):
    return "\n".join(f'<div class="stat"><span class="stat__k">{esc(k)}</span><span class="stat__v">{esc(v)}</span></div>' for k, v in pairs)

def prose_section(title, paras):
    ps = "\n".join(f"<p>{p}</p>" for p in paras)
    return f'<section class="section"><h3 class="section__title">{esc(title)}</h3><div class="prose">\n{ps}\n</div></section>'

